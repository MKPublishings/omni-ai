const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const ts = require("typescript");

function loadImageWorkerExports() {
  const workerPath = path.join(__dirname, "..", "..", "workers", "omni-ai-images", "src", "index.ts");
  const source = fs.readFileSync(workerPath, "utf8");
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020
    },
    fileName: "omni-ai-images-index.ts"
  }).outputText;

  const moduleRef = { exports: {} };
  const sandbox = {
    module: moduleRef,
    exports: moduleRef.exports,
    require,
    console,
    Response,
    Request,
    URL,
    TextEncoder,
    TextDecoder,
    Uint8Array,
    ArrayBuffer,
    setTimeout,
    clearTimeout,
    crypto
  };

  vm.runInNewContext(transpiled, sandbox, { filename: "omni-ai-images-index.vm.js" });
  return moduleRef.exports;
}

function expect(condition, message) {
  if (!condition) throw new Error(message);
}

function makeMockEnv() {
  return {
    AI: {
      async run(_model, payload) {
        const width = Number(payload?.width || 1024);
        const height = Number(payload?.height || 1024);
        if (width > 8000 || height > 8000) {
          throw new Error("model dimension limit exceeded");
        }

        const pseudoBytes = Math.max(200_000, Math.round(width * height * 0.18));
        return new Uint8Array(pseudoBytes);
      }
    }
  };
}

function makeAlwaysSmallEnv() {
  return {
    AI: {
      async run() {
        return new Uint8Array(120_000);
      }
    }
  };
}

function makeAlwaysLargeEnv() {
  return {
    AI: {
      async run() {
        return new Uint8Array(14_000_000);
      }
    }
  };
}

async function run() {
  const worker = loadImageWorkerExports();
  const {
    parseResolutionFromPrompt,
    resolveDimensions,
    generateWithinSizeRange,
    handleGenerate
  } = worker;

  expect(typeof parseResolutionFromPrompt === "function", "parseResolutionFromPrompt export missing");
  expect(typeof resolveDimensions === "function", "resolveDimensions export missing");
  expect(typeof generateWithinSizeRange === "function", "generateWithinSizeRange export missing");
  expect(typeof handleGenerate === "function", "handleGenerate export missing");

  const fourK = parseResolutionFromPrompt("create a 4k cinematic image");
  expect(fourK?.width === 3840 && fourK?.height === 2160, "4k prompt should map to 3840x2160");

  const eightKPortrait = parseResolutionFromPrompt("create an 8k portrait poster");
  expect(
    eightKPortrait?.width === 4320 && eightKPortrait?.height === 7680,
    "8k portrait prompt should map to 4320x7680"
  );

  const resolved = resolveDimensions({
    prompt: "create 8k mountain scene",
    width: 4096,
    height: 2304
  });
  expect(resolved.width === 4096 && resolved.height === 2304, "explicit request width/height should win over prompt parsing");

  const env = makeMockEnv();
  const generated = await generateWithinSizeRange(env, {
    prompt: "create an 8k ultra detailed landscape",
    negative_prompt: "",
    seed: 42
  });

  expect(generated.bytes >= 1_048_576, `generated bytes too small: ${generated.bytes}`);
  expect(generated.bytes <= 12_582_912, `generated bytes too large: ${generated.bytes}`);
  console.log(`✓ generateWithinSizeRange: ${generated.bytes} bytes in ${generated.attempts} attempts`);

  const request = new Request("https://example.com/generate", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      prompt: "create a 4k product hero render"
    })
  });

  const response = await handleGenerate(request, env);
  expect(response.status === 200, `expected 200 from handleGenerate, got ${response.status}`);

  const byteHeader = Number(response.headers.get("X-Omni-Image-Bytes") || 0);
  const statusHeader = String(response.headers.get("X-Omni-Image-Size-Status") || "");

  expect(byteHeader >= 1_048_576 && byteHeader <= 12_582_912, `response header bytes out of range: ${byteHeader}`);
  expect(statusHeader === "within", `response size status should be 'within', got '${statusHeader}'`);

  console.log("✓ handleGenerate response headers report 1-12MB in-range export");

  const impossibleRequest = new Request("https://example.com/generate", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      prompt: "create a 4k render that must fail size targeting"
    })
  });

  const impossibleResponse = await handleGenerate(impossibleRequest, makeAlwaysSmallEnv());
  expect(impossibleResponse.status === 422, `expected 422 for impossible size target, got ${impossibleResponse.status}`);

  const impossibleBody = await impossibleResponse.json();
  expect(impossibleBody?.success === false, "expected success=false for impossible size target");
  expect(
    /Unable to satisfy export size range/i.test(String(impossibleBody?.error || "")),
    "expected detailed size-range failure error"
  );
  expect(impossibleBody?.details?.status === "under", "expected details.status to be 'under'");
  console.log("✓ handleGenerate returns 422 with details when size target is unattainable");

  const oversizedRequest = new Request("https://example.com/generate", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      prompt: "create a high-detail image that must fail oversized targeting"
    })
  });

  const oversizedResponse = await handleGenerate(oversizedRequest, makeAlwaysLargeEnv());
  expect(oversizedResponse.status === 422, `expected 422 for oversized target failure, got ${oversizedResponse.status}`);

  const oversizedBody = await oversizedResponse.json();
  expect(oversizedBody?.success === false, "expected success=false for oversized target failure");
  expect(
    /Unable to satisfy export size range/i.test(String(oversizedBody?.error || "")),
    "expected detailed oversized size-range failure error"
  );
  expect(oversizedBody?.details?.status === "over", "expected details.status to be 'over'");
  console.log("✓ handleGenerate returns 422 with details when output remains oversized");

  console.log("Image worker contract smoke test passed.");
}

run().catch((error) => {
  console.error("Image worker contract smoke test failed:", error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
